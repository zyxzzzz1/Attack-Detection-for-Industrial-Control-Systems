#!/bin/bash
# Push code and config to the cluster (rsync). Only git-tracked files are pushed:
#   - excludes data/raw/, data/intel/, artifacts/, .venv/ (none of them are in git);
#   - includes tracked small files such as data/samples/ and data/mock/, which the full pytest on the cluster needs.
# Also writes .git_commit (the commit hash) for run_manifest.json on the cluster to record.
# If the worktree has uncommitted changes (including new untracked files), refuse to push and list them, so the code run on the cluster always matches the commit hash;
# --allow-dirty lets it through, in which case .git_commit and run_manifest.json are marked dirty=true.
#
# Usage:
#   scripts/push_to_cluster.sh [--dry-run] [--allow-dirty]     # push code
#   scripts/push_to_cluster.sh --data          # push HAI data (when the cluster login node has no internet)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Personal info such as cluster paths is not tracked: the real values are in cluster/local/cluster_env.sh (generated by make_cluster_jobs from config/cluster.local.yaml);
# without it, fall back to the tracked cluster/cluster_env.sh (paths are TODO, so the check below refuses to run).
CLUSTER_ENV="${ROOT}/cluster/cluster_env.sh"
if [[ -f "${ROOT}/cluster/local/cluster_env.sh" ]]; then CLUSTER_ENV="${ROOT}/cluster/local/cluster_env.sh"; fi
# shellcheck source=/dev/null
source "${CLUSTER_ENV}"

MODE=code
ALLOW_DIRTY=0
RSYNC_OPTS=(-az --info=stats1)
for arg in "$@"; do
    case "${arg}" in
        --dry-run) RSYNC_OPTS+=(--dry-run -v) ;;
        --data) MODE=data ;;
        --allow-dirty) ALLOW_DIRTY=1 ;;
        *) echo "unknown argument: ${arg}" >&2; exit 2 ;;
    esac
done

for key in CLUSTER_CODE_DIR CLUSTER_DATA_DIR; do
    if [[ "${!key}" == TODO* ]]; then
        echo "[ERROR] cluster path is still TODO (${key}): fill it in config/cluster.local.yaml (example in config/cluster.local.example.yaml)," >&2
        echo "        then run python -m scripts.make_cluster_jobs to generate cluster/local/." >&2
        exit 2
    fi
done

# The worktree check comes before connecting, so problems are found without VPN
cd "${ROOT}"
DIRTY="$(git status --porcelain)"
if [[ "${MODE}" == "code" && -n "${DIRTY}" && "${ALLOW_DIRTY}" != "1" ]]; then
    echo "[ERROR] the worktree has uncommitted changes, refusing to push (the code run on the cluster would not match the commit hash):" >&2
    echo "${DIRTY}" | sed 's/^/    /' >&2
    echo "        commit first; to really push uncommitted code add --allow-dirty (the manifest will be marked dirty=true)." >&2
    exit 3
fi

if ! ssh -o BatchMode=yes -o ConnectTimeout=10 "${CLUSTER_SSH_ALIAS}" true 2>/dev/null; then
    echo "[ERROR] cannot connect to ${CLUSTER_SSH_ALIAS}: check the Chalmers VPN (and the ${CLUSTER_SSH_ALIAS} alias and key in ~/.ssh/config)." >&2
    exit 1
fi

if [[ "${MODE}" == "data" ]]; then
    LOCAL_DATA="${HAI_DATA_DIR:-${ROOT}/data/raw/hai-21.03}"
    ssh "${CLUSTER_SSH_ALIAS}" "mkdir -p '${CLUSTER_DATA_DIR}'"
    rsync "${RSYNC_OPTS[@]}" --include='*.csv.gz' --include='download_manifest.json' --exclude='*' \
        "${LOCAL_DATA}/" "${CLUSTER_SSH_ALIAS}:${CLUSTER_DATA_DIR}/"
    echo "[DONE] data pushed to ${CLUSTER_SSH_ALIAS}:${CLUSTER_DATA_DIR} (run the verification on the cluster via srun, see the runbook)"
    exit 0
fi

COMMIT="$(git rev-parse HEAD)"
if [[ -n "${DIRTY}" ]]; then
    COMMIT="${COMMIT} dirty"
    echo "[WARN] --allow-dirty: pushing code with uncommitted changes; run_manifest.json will record dirty=true. Do not use for official runs." >&2
fi
LIST="$(mktemp)"
trap 'rm -f "${LIST}" "${ROOT}/.git_commit"' EXIT
if [[ -n "${DIRTY}" ]]; then
    git ls-files -co --exclude-standard > "${LIST}"   # When allowed, push new untracked files too (still honoring .gitignore)
else
    git ls-files > "${LIST}"
fi
echo "${COMMIT}" > "${ROOT}/.git_commit"
echo ".git_commit" >> "${LIST}"

ssh "${CLUSTER_SSH_ALIAS}" "mkdir -p '${CLUSTER_CODE_DIR}'"
rsync "${RSYNC_OPTS[@]}" --files-from="${LIST}" "${ROOT}/" "${CLUSTER_SSH_ALIAS}:${CLUSTER_CODE_DIR}/"
# Paths in the tracked job scripts are TODO; the real job scripts and cluster_env.sh are in cluster/local/ (untracked) and overwrite them in cluster/ on the cluster.
# These files are generated from the tracked templates and config/cluster.local.yaml; they are not code changes and do not affect the dirty flag.
if [[ -d "${ROOT}/cluster/local" ]]; then
    rsync "${RSYNC_OPTS[@]}" --include='*.sbatch' --include='cluster_env.sh' --exclude='*' \
        "${ROOT}/cluster/local/" "${CLUSTER_SSH_ALIAS}:${CLUSTER_CODE_DIR}/cluster/"
fi
echo "[DONE] code pushed to ${CLUSTER_SSH_ALIAS}:${CLUSTER_CODE_DIR} (commit ${COMMIT})"
echo "[INFO] files deleted locally are not deleted on the cluster automatically; clean them up there by hand if needed."
