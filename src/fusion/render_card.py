"""Alert cards (claude.md M10): enriched_alerts.json -> Markdown/HTML cards + an index page sorted by priority.

Each card contains: alert ID, start/end time, duration, score/threshold, Top-k sensors and shares, affected subsystems and criticality (with the P4 note),
intrusion paths, vulnerabilities of path assets (sorted by r_v, with KEV/EPSS marks), needs manual verification (low QoD but in KEV), recommended actions,
priority and rank, the is_mock mark, and the disclaimer.

Usage:
    python -m src.fusion.render_card [--input JSON] [--output-dir DIR] [--format md|html|both]
"""

import argparse
import json
import re
import sys
from pathlib import Path

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape

from src.utils.disclaimer import DISCLAIMER

ROOT = Path(__file__).resolve().parents[2]
STATUS_TEXT = {"scanned": "Scanned", "no_vulns": "Scanned, no vulnerabilities", "not_scanned": "Not scanned (not assessed)"}
UNDERESTIMATED = "This path contains assets that have not been assessed; the actual risk may be underestimated"
MAX_ACTION_FIXES = 5
CARD_FILE_RE = re.compile(r"^(\d+_.+|index)\.(md|html)$")  # Files generated by this module: NN_<alert ID>.ext and index.ext


def fmt_duration(seconds: int) -> str:
    h, rest = divmod(int(seconds), 3600)
    m, s = divmod(rest, 60)
    parts = ["{n} h".format(n=h) if h else "", "{n} min".format(n=m) if m else "",
             "{n} s".format(n=s) if s or not (h or m) else ""]
    return " ".join(p for p in parts if p)


def md_cell(text) -> str:
    """Markdown table cell: escape pipes and flatten line breaks."""
    return " ".join(str(text).replace("|", "\\|").split())


def build_actions(alert: dict) -> dict:
    """Recommended actions: steps are the action texts in order; fixes are OpenVAS remediation texts (the first few by r_v, deduplicated by text)."""
    assets = sorted(alert["path_assets"], key=lambda a: (-(a["R_asset"] or 0.0), a["asset"]))
    sep = ", "
    check = ["{asset} (R_asset {risk})".format(asset=a["asset"], risk=f"{a['R_asset']:.3f}")
             for a in assets if (a["R_asset"] or 0.0) > 0]
    unknown = alert["unassessed_assets"]
    steps = []
    if check:
        steps.append("Investigate these assets first: {assets}".format(assets=sep.join(check)))
    if alert["needs_review"]:
        steps.append("Manually verify whether the {n} vulnerabilities that are in KEV but have low QoD really exist".format(n=len(alert["needs_review"])))
    if unknown:
        steps.append("Assets on the path that have not been assessed (not scanned): {assets} (PLCs are not actively scanned; check them using logs and configuration)".format(assets=sep.join(unknown)))
    if any(s["note"] for s in alert["subsystems"]):
        steps.append("Follow the subsystem note and investigate the physically coupled upstream processes")
    if not steps:
        steps.append("The affected subsystems have no associated assets or vulnerabilities; assess manually using the process data")

    fixes, seen = [], set()
    for v in alert["vulns"]:
        key = " ".join((v["solution"] or "").split())
        if key and key not in seen:
            seen.add(key)
            fixes.append(v)
        if len(fixes) >= MAX_ACTION_FIXES:
            break
    return {"steps": steps, "fixes": fixes}


def exposure(alert: dict) -> str:
    """Assessment status of the alert-level E_sub (display only): assessed / partial (some path assets unscanned) /
    not_assessed (all path assets unscanned)."""
    n_unassessed = len(alert["unassessed_assets"])
    if not n_unassessed:
        return "assessed"
    return "not_assessed" if n_unassessed == len(alert["path_assets"]) else "partial"


def shown_subsystems(alert: dict, digits: int = 0) -> list[dict]:
    """Subsystems shown in the list: those whose weight rounds to 0 at display precision (decimal places of the percentage) are hidden."""
    return [s for s in alert["subsystems"] if round(s["weight"] * 100, digits) > 0]


def card_context(alert: dict, meta: dict) -> dict:
    return {
        "a": alert,
        "meta": meta,
        "n_alerts": len(meta["alerts"]),
        "duration": fmt_duration(alert["duration_s"]),
        "ratio": alert["max_score"] / alert["threshold"],
        "actions": build_actions(alert),
        "status_text": STATUS_TEXT,
        "disclaimer": DISCLAIMER,
    }


def card_name(alert: dict, ext: str) -> str:
    return f"{alert['rank']:02d}_{alert['alert_id']}.{ext}"


def make_env(templates_dir: Path) -> Environment:
    env = Environment(
        loader=FileSystemLoader(str(templates_dir)),
        autoescape=select_autoescape(enabled_extensions=("html.j2",), default_for_string=False),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    env.filters["md"] = md_cell
    env.filters["pct"] = lambda x: f"{x * 100:.1f}%"
    env.filters["f3"] = lambda x: f"{x:.3f}"
    # Asset risk: not assessed (None) is not shown as 0
    env.filters["risk"] = lambda x: "Not assessed" if x is None else f"{x:.3f}"
    env.globals["UNDERESTIMATED"] = UNDERESTIMATED
    env.globals["card_name"] = card_name
    env.globals["exposure"] = exposure
    env.globals["shown_subsystems"] = shown_subsystems
    return env


def render_all(meta: dict, env: Environment, out_dir: Path, formats: list[str], limit: int | None = None) -> list[Path]:
    """limit: generate cards and index entries only for the top limit alerts by priority (None or 0 means all).
    The "x / n" on cards still counts all alerts. Cards and index pages from the previous run in the output directory are removed first, so old and new are not mixed."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.iterdir():
        if old.is_file() and CARD_FILE_RE.match(old.name):
            old.unlink()
    written = []
    alerts = sorted(meta["alerts"], key=lambda a: a["rank"])[:limit or None]
    for ext in formats:
        card_t = env.get_template(f"alert_card.{ext}.j2")
        for a in alerts:
            path = out_dir / card_name(a, ext)
            path.write_text(card_t.render(**card_context(a, meta)), encoding="utf-8")
            written.append(path)
        index = out_dir / f"index.{ext}"
        index.write_text(env.get_template(f"index.{ext}.j2").render(
            meta=meta, alerts=alerts, n_total=len(meta["alerts"]), disclaimer=DISCLAIMER), encoding="utf-8")
        written.append(index)
    return written


def main() -> int:
    p = argparse.ArgumentParser(description="enriched_alerts.json → alert cards + index page")
    p.add_argument("--config", type=Path, default=ROOT / "config" / "config.yaml")
    p.add_argument("--input", type=Path, help="defaults to fusion.enriched_alerts_json in config.yaml")
    p.add_argument("--output-dir", type=Path, help="defaults to fusion.cards_dir in config.yaml")
    p.add_argument("--format", choices=["md", "html", "both"], default="both")
    p.add_argument("--limit", type=int, help="render only the top N by priority, defaults to fusion.max_rendered_alerts in config.yaml")
    args = p.parse_args()
    with open(args.config, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)["fusion"]
    meta = json.loads((args.input or ROOT / cfg["enriched_alerts_json"]).read_text(encoding="utf-8"))
    formats = ["md", "html"] if args.format == "both" else [args.format]
    env = make_env(ROOT / cfg["templates_dir"])
    limit = cfg.get("max_rendered_alerts") if args.limit is None else args.limit
    written = render_all(meta, env, args.output_dir or ROOT / cfg["cards_dir"], formats, limit)
    print(f"[SAVED] {len(written)} files → {written[0].parent} (is_mock={meta.get('is_mock')})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
